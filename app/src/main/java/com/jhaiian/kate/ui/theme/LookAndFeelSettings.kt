    fun save(context: Context) {
        ThemePreferences.setTheme(context, theme)
        ThemePreferences.setAccent(context, accent)
        ThemePreferences.setIntensity(context, intensity)
        ThemePreferences.setAppArtworkColors(context, appArtworkColors)
        ThemePreferences.setPlayerArtworkColors(context, playerArtworkColors)
        ThemePreferences.saveColorEngine(context, paletteStyle, contrast, customAccent, colorOverrides)
        DisplayPreferences.setHideStatusBar(context, hideStatusBar)
        DisplayPreferences.setHideNavigationBar(context, hideNavigationBar)
        MotionPreferences.setHaptics(context, haptics)
        MotionPreferences.setAnimationSpeed(context, animationSpeed)
        DisplayPreferences.setFontStyle(context, fontStyle)
        DisplayPreferences.setTextSize(context, textSize)
        DisplayPreferences.saveImages(context, appBackgroundImage, playerBackgroundImage, imageBlur, imageDim)
        PlayerStylePreferences.setTitleWeight(context, playerTitleWeight)
        PlayerStylePreferences.saveBuilder(
            context,
            slotLeft = playerSlotLeft,
            slotInnerLeft = playerSlotInnerLeft,
            slotInnerRight = playerSlotInnerRight,
            slotRight = playerSlotRight,
            quickList = playerQuickList,
            seekStep = seekStepSeconds,
            longPress = playerLongPress,
            doubleTapSides = playerDoubleTapSides,
            miniLongPress = miniLongPress,
            infoFields = playerInfoFields,
            layoutLandscape = playerLayoutLandscape
        )
        LyricsPreferences.setFont(context, lyricsFont)
        LyricsPreferences.saveExtras(context, lyricsActiveColor, lyricsInactiveColor, lyricsLineSpacing)
        VisualizerPreferences.save(
            context,
            style = visualizerStyle,
            placements = visualizerPlacements,
            bars = visualizerBars,
            sensitivity = visualizerSensitivity,
            smoothing = visualizerSmoothing,
            color = visualizerColor,
            customColor = visualizerCustomColor,
            fps = visualizerFps
        )
        PlayerStylePreferences.save(
            context,
            artShape = playerArtShape,
            artSize = playerArtSize,
            background = playerBackground,
            glow = playerGlow,
            showShuffle = playerShowShuffle,
            showRepeat = playerShowRepeat,
            showFavorite = playerShowFavorite,
            swipeArtwork = playerSwipeArtwork,
            doubleTap = playerDoubleTap,
            miniSwipeSkip = miniSwipeSkip,
            miniSwipeDismiss = miniSwipeDismiss,
            layout = playerLayout,
            vinylSpeed = playerVinylSpeed,
            vinylTonearm = playerVinylTonearm,
            cassetteColor = playerCassetteColor,
            coverPreview = playerCoverPreview,
            header = playerHeader,
            showHandle = playerShowHandle,
            showCollapse = playerShowCollapse,
            showQueueButton = playerShowQueueButton,
            showMenuButton = playerShowMenuButton,
            showAudioChip = playerShowAudioChip,
            infoAlign = playerInfoAlign,
            titleSize = playerTitleSize,
            showAlbum = playerShowAlbum,
            marquee = playerMarquee,
            lyricLine = playerLyricLine,
            quickActions = playerQuickActions,
            skipButtons = playerSkipButtons,
            artShadow = playerArtShadow,
            backdropStrength = playerBackdropStrength
        )
        SeekBarPreferences.save(
            context,
            style = seekStyle,
            thumb = seekThumb,
            thickness = seekThickness,
            color = seekColor,
            bubble = seekBubble,
            lyricMarkers = seekLyricMarkers,
            waveShape = seekWaveShape,
            waveDensity = seekWaveDensity,
            squiggleHeight = seekSquiggleHeight,
            squiggleLength = seekSquiggleLength,
            squiggleSpeed = seekSquiggleSpeed,
            squiggleReactive = seekSquiggleReactive
        )
        LyricsPreferences.save(
            context,
            textSize = lyricsTextSize,
            alignment = lyricsAlignment,
            softenLines = lyricsSoftenLines,
            immersive = lyricsImmersive,
            keepScreenOn = lyricsKeepScreenOn,
            wordByWord = lyricsWordByWord,
            lineSweep = lyricsLineSweep,
            wordStyle = lyricsWordStyle,
            background = lyricsBackground
        )
        LibraryStylePreferences.save(
            context,
            corners = libraryCorners,
            showBadges = libraryShowBadges,
            showDuration = libraryShowDuration,
            showScrollbar = showScrollbar,
            alphabetIndex = libraryAlphabetIndex
        )
        HomePreferences.setHiddenSections(context, homeHiddenSections)
        LibraryLayoutPreferences.save(
            context,
            categoryOrder = libraryCategoryOrder,
            hiddenCategories = libraryHiddenCategories,
            homeOrder = homeSectionOrder,
            homePins = homePins,
            songTitle = songTitleSource,
            songFields = songSubtitleFields,
            songTrackNumber = songShowTrackNumber,
            songTap = songTapAction,
            tapOpensPlayer = songTapOpensPlayer
