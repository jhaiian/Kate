            context,
            tabOrder = navTabOrder,
            hiddenTabs = navHiddenTabs,
            labels = navLabels,
            startScreen = startScreen,
            miniPlayer = miniPlayerStyle,
            twoPane = twoPane
        )
        MiniProgressPreferences.save(
            context,
            style = miniProgressStyle,
            matchPlayer = miniProgressMatchPlayer,
            thickness = miniProgressThickness,
